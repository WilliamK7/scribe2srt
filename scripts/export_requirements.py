"""Generate or check the pip compatibility files against the locked uv project."""

import argparse
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parent.parent
EXPORT_ARGS = ("export", "--locked", "--no-emit-project", "--no-hashes", "--no-annotate", "--no-header")


def export_requirements(uv="uv", check=False):
    configuration = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    version = configuration["tool"]["uv"]["required-version"].removeprefix("==")
    exports = {}
    for filename, group in (("requirements.txt", ()), ("requirements-build.txt", ("--group", "build"))):
        arguments = [*EXPORT_ARGS, *group]
        result = subprocess.run([uv, *arguments], cwd=ROOT, check=True,
                                stdout=subprocess.PIPE, text=True, encoding="utf-8")
        header = (f"# Autogenerated by uv {version} from pyproject.toml and uv.lock; do not edit.\n"
                  "# Regenerate: uv run --locked python scripts/export_requirements.py\n"
                  f"# Export: uv {' '.join(arguments)}\n\n")
        exports[filename] = header + result.stdout
    if check:
        different = [filename for filename, content in exports.items()
                     if not (ROOT / filename).is_file()
                     or (ROOT / filename).read_text(encoding="utf-8") != content]
        if different:
            raise RuntimeError(f"Requirements exports differ from uv.lock: {', '.join(different)}; "
                               "run uv run --locked python scripts/export_requirements.py")
        print("Both requirements exports match uv.lock", flush=True)
    else:
        for filename, content in exports.items():
            (ROOT / filename).write_text(content, encoding="utf-8", newline="\n")
            print(f"Exported {filename}", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if either committed export is stale")
    parser.add_argument("--uv", default="uv", help="uv executable to use for both locked exports")
    arguments = parser.parse_args()
    export_requirements(arguments.uv, arguments.check)
